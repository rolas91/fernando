const assert = require('node:assert/strict');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { load } = require('./pagination-harness.cjs');
const loading = load('components/shared/TableLoading.tsx');
const Catalog = load('components/shared/CatalogQueryState.tsx', { './TableLoading': loading }).default;
const Assignment = load('components/shared/AssignmentReadState.tsx', { './TableLoading': loading }).AssignmentReadState;
const markup = (Component, props) => renderToStaticMarkup(React.createElement(Component, props));
const initial = markup(loading.default, { label: 'Loading workers…' });
assert(initial.includes('role="status"'));
assert(initial.includes('aria-busy="true"'));
assert(initial.includes('Loading workers…'));
assert(initial.includes('aria-hidden="true"'));
assert(initial.includes('motion-safe:animate-spin'));
assert(initial.includes('motion-safe:animate-pulse'));
const refresh = markup(Catalog, { loading: false, refreshing: true, error: null, retry() {} });
assert(refresh.includes('Updating data…'));
assert(!refresh.includes('grid-template-columns'));
const failure = markup(Catalog, { loading: true, refreshing: true, error: Error('Read failed'), retry() {} });
assert(failure.includes('role="alert"') && failure.includes('Retry loading'));
assert(!failure.includes('animate-pulse'));
assert.equal(markup(Catalog, { loading: false, error: null, retry() {} }), '');
assert(markup(Assignment, { pending: true, failed: false, retry() {} }).includes('Loading assignments…'));
const assignmentError = markup(Assignment, { pending: true, failed: true, retry() {} });
assert(assignmentError.includes('Unable to load assignments.'));
assert(!assignmentError.includes('animate-pulse'));
assert(markup(Assignment, { pending: false, failed: false, refreshing: true, retry() {} }).includes('Updating assignments…'));
assert(!markup(loading.default, { variant: 'inline', announce: false }).includes('role="status"'));
console.log('Shared table loading: accessible initial state, reduced-motion support, non-destructive background indicator, errors/retry priority and empty-state cleanup passed.');
